"""
new_skill.py — scaffold a new Meryna skill in seconds.

Usage
-----
    python new_skill.py <skill-name> [-d "Short description"]

Examples
--------
    python new_skill.py timer
    python new_skill.py "unit converter" -d "Converts between units of measure."

This creates ``skills/<skill-name>/`` containing the three files every skill
needs (``manifest.json``, ``<module>.py``, ``__init__.py``), pre-filled and
ready to edit.  No core files are touched — restart Meryna and the new skill
is auto-discovered.

The script refuses to overwrite an existing skill folder.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

SKILLS_DIR = Path(__file__).resolve().parent / "skills"


def _slug(name: str) -> str:
    """'Unit Converter' -> 'unit-converter' (folder + manifest name base)."""
    s = re.sub(r"[^a-zA-Z0-9]+", "-", name).strip("-").lower()
    return re.sub(r"-{2,}", "-", s)


def _module(slug: str) -> str:
    """'unit-converter' -> 'unit_converter' (python module / file name)."""
    return slug.replace("-", "_")


def _class(slug: str) -> str:
    """'unit-converter' -> 'UnitConverterSkill' (python class name)."""
    parts = [p for p in slug.split("-") if p]
    return "".join(p.capitalize() for p in parts) + "Skill"


def _intent(slug: str) -> str:
    """'unit-converter' -> 'unit_converter_intent'."""
    return _module(slug) + "_intent"


MANIFEST_TEMPLATE = {
    "version": "1.0.0",
    "default_enabled": True,
    "permissions": ["network"],
}

SKILL_CODE = '''\
"""
{Class} — {description}

Auto-generated by new_skill.py.  Fill in the logic inside ``execute()``.
See skills/_template/example.py for a fully-commented reference.
"""

from __future__ import annotations

import logging
from typing import Any

from meryna_platform.models import SkillContext, SkillResponse
from skills.base import Skill

logger = logging.getLogger("meryna.skills.{module}")


class {Class}(Skill):
    """{description}"""

    def __init__(self, ai_provider: Any) -> None:
        super().__init__(ai_provider)

    @property
    def name(self) -> str:
        return "{slug}"

    @property
    def version(self) -> str:
        return "1.0.0"

    async def execute(self, context: SkillContext) -> SkillResponse:
        # context.utterance / .entities / .conversation_history /
        # .user_preferences are available. self._ai_provider.generate_text(...)
        # is available if you need AI generation. Keep replies TTS-friendly.
        reply = "The {slug} isn't implemented yet. Edit skills/{slug}/{module}.py."
        return SkillResponse(text=reply)
'''

INIT_CODE = '"""{Title} skill package."""\n'


def create_skill(name: str, description: str) -> int:
    slug = _slug(name)
    if not slug:
        print(f"error: '{name}' is not a valid skill name.", file=sys.stderr)
        return 2

    module = _module(slug)
    class_name = _class(slug)
    skill_dir = SKILLS_DIR / slug

    if skill_dir.exists():
        print(
            f"error: skills/{slug}/ already exists. "
            "Choose a different name or delete it first.",
            file=sys.stderr,
        )
        return 1

    if not SKILLS_DIR.exists():
        print(f"error: skills directory not found at {SKILLS_DIR}", file=sys.stderr)
        return 1

    manifest = {
        "name": slug,
        **MANIFEST_TEMPLATE,
        "description": description,
        "entry_point": f"{module}:{class_name}",
        "intents": [
            {
                "intent_name": _intent(slug),
                "description": (
                    f"Describe WHEN Meryna should use the {slug}. "
                    "Edit this — the AI reads it to route requests."
                ),
                "example_utterances": [
                    f"Use the {name}",
                    f"Run {name} for me",
                    f"Can you do {name}?",
                    "Add three more realistic phrases users would say",
                ],
            }
        ],
    }
    # Put "name" and "description" first for readability.
    ordered = {
        "name": manifest["name"],
        "version": manifest["version"],
        "description": manifest["description"],
        "entry_point": manifest["entry_point"],
        "default_enabled": manifest["default_enabled"],
        "permissions": manifest["permissions"],
        "intents": manifest["intents"],
    }

    skill_dir.mkdir(parents=True)
    (skill_dir / "manifest.json").write_text(
        json.dumps(ordered, indent=2) + "\n", encoding="utf-8"
    )
    (skill_dir / f"{module}.py").write_text(
        SKILL_CODE.format(
            Class=class_name, module=module, slug=slug, description=description
        ),
        encoding="utf-8",
    )
    (skill_dir / "__init__.py").write_text(
        INIT_CODE.format(Title=name.title()), encoding="utf-8"
    )

    print(f"Created skill '{slug}':")
    print(f"  skills/{slug}/manifest.json")
    print(f"  skills/{slug}/{module}.py   (class {class_name})")
    print(f"  skills/{slug}/__init__.py")
    print()
    print("Next steps:")
    print(f"  1. Edit skills/{slug}/manifest.json — refine the description and")
    print("     example_utterances (these teach the AI when to use the skill).")
    print(f"  2. Implement the logic in skills/{slug}/{module}.py execute().")
    print("  3. Restart Meryna — the skill is auto-discovered.")
    return 0


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Scaffold a new Meryna skill (folder + 3 files)."
    )
    parser.add_argument(
        "name",
        help='Skill name, e.g. "timer" or "unit converter".',
    )
    parser.add_argument(
        "-d",
        "--description",
        default="",
        help="One-line description of what the skill does.",
    )
    args = parser.parse_args()

    description = args.description.strip() or f"Handles {args.name} requests."
    sys.exit(create_skill(args.name, description))


if __name__ == "__main__":
    main()
